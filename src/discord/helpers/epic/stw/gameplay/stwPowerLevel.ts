function lookupPower(rarity: string, level: number): number {
  const table = STW_NIVELES_REALES[rarity];
  if (!table) return level;
  if (table[level] !== undefined) return table[level];
  const keys = Object.keys(table).map(Number).sort((a, b) => a - b);
  for (let i = keys.length - 1; i >= 0; i--) {
    if (keys[i] <= level) return table[keys[i]];
  }
  return level;
}

/** Display power from in-game schematic level + rarity (same as /heroes cards). */
export function getStwPowerLevel(rarity: string, gameLevel: number): number {
  if (!(gameLevel > 0)) return 0;
  const powerRarity = rarity === 'er' || rarity === 'ssr' || rarity === 'ur' ? 'sr' : rarity;
  return lookupPower(powerRarity, gameLevel);
}
